# SDoH correlations (spoke-okn) — statistical (ecological, county-level)
def pearson(n, sx, sy, sxy, sxx, syy):
    """Compute the Pearson correlation from summary statistics."""
    num = n * sxy - sx * sy
    den = math.sqrt((n * sxx - sx * sx) * (n * syy - sy * sy))
    return num / den if den else 0


sdoh = []
for var, n, sx, sy, sxy, sxx, syy in SDOH_SUMS:
    r = pearson(n, sx, sy, sxy, sxx, syy)
    sdoh.append((var, r, n))
    row(
        entity_type="sdoh_correlation",
        entity=var,
        relationship="correlates_with_county_diabetes_prevalence",
        sources="spoke-okn",
        n_sources=1,
        evidence_types="statistical_association",
        best_score=f"{r:+.3f}",
        score_type="pearson_r",
        confidence_tier=("T2 high" if abs(r) >= 0.5 else "T3 medium"),
        notes=f"County Health Rankings; n={n} counties",
    )

