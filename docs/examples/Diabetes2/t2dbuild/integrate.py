def tier(nsrc, w):
    """Assign a confidence tier from source count and best score."""
    if nsrc >= 4:
        return "T1 very-high"
    if nsrc == 3 or (w and w >= 5.0):
        return "T2 high"
    if nsrc == 2 or (w and w >= 3.5):
        return "T3 medium"
    return "T4 low"


